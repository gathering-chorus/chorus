//! #4465 — chorus-make: a pipeline's steps and skills, as rows from the graph,
//! become the werk v2 workflow that dagu runs.
//!
//! Jeff 2026-10-09: "we design, code, test chorus-make … use chorus-make to
//! generate a new werk pipeline that is a new major version … run cards against
//! werk v1 and also against werk v2 so we have a fallback path when v2 breaks".
//!
//! One row per (PipelineStep, StepSkill, Skill), tab-separated, in this column
//! order (the SPARQL SELECT writes the same):
//!
//!   step  stepOrder  skillOrder  skill  label  executor  implementedBy  mode
//!
//! Each skill becomes one dagu step, in step order then skill order, each
//! depending on the one before. A deterministic skill runs
//! `<implementedBy> <mode>`; a human skill (Jeff's go) is a dagu `human.task`.
//! The same rows always give the same bytes.

pub const HEADER: &str =
    "# GENERATED by chorus-make from the graph (#4465). Do not edit: change the rows and regenerate.\n";

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Row {
    pub step: String,
    pub step_order: u32,
    pub skill_order: u32,
    pub skill: String,
    pub label: String,
    pub executor: String,
    pub implemented_by: String,
    pub mode: String,
    /// #4456 — the value-stream step a failure of this step routes to (the
    /// step's `onFail`), as its local name; empty when the step names none.
    pub on_fail: String,
    /// #4514 AC4 — the skill's input shape when it is a runner tool. Such a step
    /// calls the verb through the runner (one path: dagu calls the runner too).
    pub input_shape: String,
    /// #4514 reopen 1 — the step's own key=value pairs for a runner tool
    /// (atomic=true, mode=ff): the pipeline's choices, from the StepSkill row.
    pub with_args: String,
}

/// Rows from TSV. A line with the wrong column count or a non-number order is
/// refused by line number, never skipped.
pub fn parse_rows(tsv: &str) -> Result<Vec<Row>, Vec<String>> {
    let mut rows = Vec::new();
    let mut errs = Vec::new();
    for (i, line) in tsv.lines().enumerate() {
        let line = line.trim_end_matches('\r');
        if line.trim().is_empty() || line.starts_with('#') || line.starts_with("step\t") {
            continue;
        }
        let f: Vec<&str> = line.split('\t').collect();
        // #4514 — a 10th column (inputShape) is optional, so older row files still read
        if !(9..=11).contains(&f.len()) {
            errs.push(format!("line {}: {} columns, want 9 to 11", i + 1, f.len()));
            continue;
        }
        let (so, ko) = (f[1].trim().parse::<u32>(), f[2].trim().parse::<u32>());
        match (so, ko) {
            (Ok(step_order), Ok(skill_order)) => rows.push(Row {
                step: f[0].trim().into(),
                step_order,
                skill_order,
                skill: f[3].trim().into(),
                label: f[4].trim().into(),
                executor: f[5].trim().into(),
                implemented_by: f[6].trim().into(),
                mode: f[7].trim().into(),
                on_fail: local(f[8].trim()),
                input_shape: f.get(9).map(|x| local(x.trim())).unwrap_or_default(),
                with_args: f.get(10).map(|x| x.trim().to_string()).unwrap_or_default(),
            }),
            _ => errs.push(format!("line {}: stepOrder and skillOrder must be numbers", i + 1)),
        }
    }
    if errs.is_empty() { Ok(rows) } else { Err(errs) }
}

/// What the door cannot check (it does not run sh:sparql, athena-model
/// lib.rs:4453), chorus-make refuses before it writes anything.
pub fn check(rows: &[Row]) -> Vec<String> {
    let mut errs = Vec::new();
    // #4514 — a runner step that cannot fill a required argument never runs
    for r in rows.iter().filter(|r| !r.input_shape.is_empty()) {
        let (_, missing) = runner_pairs(r);
        if !missing.is_empty() {
            errs.push(format!("step {} calls {} without {}: add it to the step's withArguments", r.step, runner_tool_name(r), missing.join(", ")));
        }
    }
    if rows.is_empty() {
        errs.push("no rows: a pipeline with no steps is refused, never written empty".into());
    }
    let mut seen = std::collections::BTreeSet::new();
    let mut names = std::collections::BTreeSet::new();
    for r in rows {
        for arg in r.with_args.split_whitespace() {
            if let Some(cond) = arg.strip_prefix("precondition=") {
                if !cond.contains('=') {
                    errs.push(format!("{}: precondition '{cond}' missing '=' separator (expected condition=value)", r.skill));
                }
            }
        }
        match r.executor.as_str() {
            "deterministic" if r.implemented_by.is_empty() => errs.push(format!(
                "{}: a deterministic skill needs implementedBy (the binary that runs it)", r.skill)),
            "deterministic" | "human" => {}
            // #4540 — a step that runs a whole child pipeline (`call:`)
            "pipeline" if r.implemented_by.is_empty() => errs.push(format!(
                "{}: a pipeline skill needs implementedBy (the Pipeline it calls)", r.skill)),
            "pipeline" => {}
            "agent" => errs.push(format!(
                "{}: an agent skill cannot run inside the v2 workflow yet", r.skill)),
            other => errs.push(format!("{}: unknown executor '{}'", r.skill, other)),
        }
        if !names.insert(dagu_name(rows, r)) {
            errs.push(format!("{}: called twice in one step; dagu step names must be unique", r.skill));
        }
        // #4502 — skills sharing a step's order run in parallel (the demo's
        // gates and reviews); a human step must hold its order alone.
        let at_order = || rows.iter().filter(|o| o.step == r.step && o.skill_order == r.skill_order);
        if !seen.insert((r.step.clone(), r.skill_order)) {
            let names: Vec<&str> = at_order().map(|o| o.skill.as_str()).collect();
            if at_order().any(|o| o.executor == "human") {
                errs.push(format!("{} share order {} in step {} with a human step; a human step stands alone", names.join(", "), r.skill_order, r.step));
            } else if !at_order().all(|o| o.with_args.split_whitespace().any(|p| p == PARALLEL)) {
                // #4502 (Abby's review) — a shared order is parallel only when
                // every row says so; an accidental collision is refused, never
                // silently fanned out
                errs.push(format!("{} share order {} in step {}; mark every one {} to run them in parallel", names.join(", "), r.skill_order, r.step, PARALLEL));
            }
        }
    }
    errs
}

/// dagu step name: the Skill row's own name (`skill-werk-deploy-demo`),
/// never one chorus-make makes up (Jeff via Silas 2026-10-09 20:34). dagu's
/// `name` takes hyphens; its `id` does not, so no id is written. The verb
/// alone is not unique (werk-deploy runs three skills).
pub fn step_name(r: &Row) -> String {
    r.skill.rsplit(['#', '/']).next().unwrap_or(&r.skill).to_string()
}

/// #4515 — the dagu step name of a row among its pipeline's rows. A skill the
/// pipeline calls from one step only is named by its Skill row (step_name); a
/// skill two steps call (athena's Model and Validate both run athena-validate)
/// is the Skill row's name and the pipeline step's: `skill-athena-validate-shape`.
/// Both parts are graph names; nothing is minted. The same skill twice in ONE
/// step still collides, and check() refuses it.
pub fn dagu_name(rows: &[Row], r: &Row) -> String {
    let n = step_name(r);
    if rows.iter().any(|o| o.step != r.step && step_name(o) == n) {
        format!("{n}-{}", r.step)
    } else {
        n
    }
}

