//! #4499 — code units and their dependencies come from the build files, on
//! every land. Jeff, 2026-10-11 10:00: "this feels like a volatile data set".
use chorus_crawl::code::*;

fn read_from(files: &'static [(&'static str, &'static str)]) -> impl Fn(&str) -> Option<String> {
    move |p: &str| files.iter().find(|(f, _)| *f == p).map(|(_, t)| t.to_string())
}

const TREE: &[(&str, &str)] = &[
    ("platform/services/werk-accept/Cargo.toml", "[dependencies]\nwerk-teardown = { path = \"../werk-teardown\" }\nserde = \"1\"\n"),
    ("platform/services/werk-teardown/Cargo.toml", "[package]\nname = \"werk-teardown\"\n"),
    ("directing/products/pulse/api/Cargo.toml", "# Generated by athena-gen (#4490) — DO NOT EDIT\n[dependencies]\nchorus-oidc = { path = \"../../../../platform/services/chorus-oidc\" }\n"),
    ("platform/services/chorus-oidc/Cargo.toml", "[package]\nname = \"chorus-oidc\"\n"),
    ("platform/api/package.json", "{\"dependencies\":{\"sdk\":\"file:../chorus-sdk\"}}"),
    ("platform/chorus-sdk/package.json", "{\"name\":\"sdk\"}"),
];

fn tree() -> Vec<Unit> {
    let cargo: Vec<String> = TREE.iter().filter(|(f, _)| f.ends_with("Cargo.toml")).map(|(f, _)| f.to_string()).collect();
    let pkgs: Vec<String> = TREE.iter().filter(|(f, _)| f.ends_with("package.json")).map(|(f, _)| f.to_string()).collect();
    let sources = |d: &str| if d.ends_with("werk-accept") { vec!["include!(\"../../shared/crate_dirs.rs\");".to_string()] } else { vec![] };
    units(&cargo, &pkgs, &read_from(TREE), &sources)
}

fn unit<'a>(us: &'a [Unit], p: &str) -> &'a Unit {
    us.iter().find(|u| u.path == p).unwrap_or_else(|| panic!("no unit {p}"))
}

#[test]
fn crate_package_model_and_include_edges_come_from_the_build_files() {
    let us = tree();
    assert_eq!(unit(&us, "platform/services/werk-accept").deps, vec!["platform/services/shared", "platform/services/werk-teardown"]);
    assert_eq!(unit(&us, "platform/api").deps, vec!["platform/chorus-sdk"]);
    let gen = &unit(&us, "directing/products/pulse/api").deps;
    assert!(gen.contains(&"platform/services/chorus-oidc".to_string()));
    assert!(gen.contains(&"roles/silas/ontology".to_string()), "a generated API depends on the model: {gen:?}");
    assert_eq!(unit(&us, "platform/services/shared").kind, "include");
}

#[test]
fn the_blast_radius_of_a_unit_is_its_dependents_through_the_graph() {
    let us = tree();
    assert_eq!(dependents("platform/services/werk-teardown", &us), vec!["platform/services/werk-accept"]);
    let model = dependents("roles/silas/ontology", &us);
    assert_eq!(model, vec!["directing/products/pulse/api"]);
}

#[test]
fn negative_proof_a_dropped_dependency_disappears_on_the_next_crawl() {
    let before = tree();
    let desired = |us: &[Unit]| us.iter().map(|u| { let f = unit_fields(u); (f[0].1.clone(), f[1..].to_vec()) }).collect::<Vec<_>>();
    let current = desired(&before);
    // werk-accept drops werk-teardown from its Cargo.toml
    let mut after = before.clone();
    after.iter_mut().find(|u| u.path == "platform/services/werk-accept").unwrap().deps.retain(|d| !d.ends_with("werk-teardown"));
    let p = plan_units(&desired(&after), &current);
    assert_eq!(p.update.len(), 1, "{p:?}");
    let (name, fields) = &p.update[0];
    assert_eq!(name, "platform-services-werk-accept");
    assert!(!fields.iter().any(|(k, v)| k == "dependsOn" && v.ends_with("werk-teardown")), "the old edge must not be written back");
    // and a second crawl over the same tree writes nothing
    assert_eq!(plan_units(&desired(&after), &desired(&after)).unchanged, after.len());
}

#[test]
fn a_unit_no_build_file_states_is_deleted() {
    let us = tree();
    let mut current: Vec<(String, Vec<(String, String)>)> = us.iter().map(|u| { let f = unit_fields(u); (f[0].1.clone(), f[1..].to_vec()) }).collect();
    current.push(("platform-services-gone".into(), vec![("unitPath".into(), "platform/services/gone".into())]));
    let desired: Vec<_> = current[..current.len() - 1].to_vec();
    assert_eq!(plan_units(&desired, &current).delete, vec!["platform-services-gone"]);
}

#[test]
fn negative_proof_a_file_in_no_unit_has_no_unit_and_an_edge_to_nowhere_is_never_written() {
    let us = tree();
    assert!(unit_of("designing/docs/x.html", &us).is_none(), "a file in no unit must read as unknown, not as no blast radius");
    assert_eq!(unit_of("platform/services/werk-accept/src/lib.rs", &us).unwrap().path, "platform/services/werk-accept");
    // a path dependency on a crate that is not in the tree is dropped, not dangled
    let lone = units(&["platform/services/a/Cargo.toml".into()], &[],
        &|_| Some("x = { path = \"../missing\" }".to_string()), &|_| vec![]);
    assert!(lone.iter().find(|u| u.path == "platform/services/a").unwrap().deps.is_empty());
}
