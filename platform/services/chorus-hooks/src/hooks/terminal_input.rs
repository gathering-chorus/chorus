//! #4628 — what Jeff types in a role's terminal reaches Buzz once, through pulse.
//!
//! Measured 2026-10-19: of Jeff's 469 messages in Buzz that day, 393 came only
//! from Clearing v1's transcript tailer, which also wrote every one of the
//! day's 110 doubles. The UserPromptSubmit hook sees each prompt as it is
//! typed, so it posts the text to pulse (`/api/record`, kind jeff, record only)
//! and v1's copy can go.
//!
//! Only what Jeff typed or pasted counts. A prompt can also be something the
//! harness put there — a peer nudge, a task notification, Stop-hook feedback,
//! a system notice — and those are skipped here. A Clearing message pulse
//! delivered into the terminal is skipped by pulse, which holds that row.
//!
//! The post never holds the prompt up (Wren, after #4644's Stop-hook
//! timeouts): it runs off the request, with a 1 s cap, and a miss is a spine
//! line, not an error.

use crate::state::chorus_log;

/// Prompts that start with one of these were put there by the harness or a
/// peer, not typed by Jeff.
const INJECTED: &[&str] = &[
    "[nudge from ",
    "<task-notification>",
    "Stop hook feedback:",
    "[SYSTEM NOTIFICATION",
    "<system-reminder>",
    "<local-command-",
    "Caveat: The messages below were generated by the user while running local commands",
];

fn between<'a>(s: &'a str, open: &str, close: &str) -> Option<&'a str> {
    let start = s.find(open)? + open.len();
    let end = s[start..].find(close)? + start;
    Some(&s[start..end])
}

/// The words to record for this prompt, or None when Jeff didn't type it.
/// A slash command is recorded as the line he typed (`/pair wren 4628`), not
/// the skill text the harness expanded it into.
pub fn typed_text(prompt: &str) -> Option<String> {
    let p = prompt.trim();
    if p.is_empty() {
        return None;
    }
    if let Some(name) = between(p, "<command-name>", "</command-name>") {
        let args = between(p, "<command-args>", "</command-args>").unwrap_or("").trim();
        let name = name.trim();
        let name = if name.starts_with('/') { name.to_string() } else { format!("/{name}") };
        return Some(if args.is_empty() { name } else { format!("{name} {args}") });
    }
    if INJECTED.iter().any(|s| p.starts_with(s)) {
        return None;
    }
    Some(p.to_string())
}

fn pulse_secret() -> Option<String> {
    std::env::var("CHORUS_PULSE_SECRET").ok().or_else(|| {
        let p = std::env::var("CHORUS_PULSE_SECRET_FILE").unwrap_or_else(|_| {
            format!("{}/.chorus/pulse-nudge.secret", std::env::var("HOME").unwrap_or_default())
        });
        std::fs::read_to_string(p).ok().map(|s| s.trim().to_string())
    })
    .filter(|s| !s.is_empty())
}

/// What to do with one prompt: nothing, a logged miss, or a post.
#[derive(Debug, PartialEq)]
pub enum Plan {
    Skip,
    Miss(&'static str),
    Post { text: String, secret: String },
}

/// The secret is read by the daemon itself, never taken from the shim's env:
/// the shim forwards only named env (Wren, 09-09), so a credential there would
/// never arrive and every post would fail quietly.
pub fn plan(prompt: &str, secret: Option<String>) -> Plan {
    let Some(text) = typed_text(prompt) else { return Plan::Skip };
    match secret {
        Some(secret) => Plan::Post { text, secret },
        None => Plan::Miss("no pulse secret"),
    }
}

/// Post the typed text for `role`'s pane. Fire and forget: spawned, 1 s cap.
pub fn record(role: &str, prompt: &str) {
    let (text, secret) = match plan(prompt, pulse_secret()) {
        Plan::Skip => return,
        Plan::Miss(why) => {
            let r = role.to_string();
            tokio::spawn(async move { chorus_log("terminal.input.unrecorded", &r, &[("error", why)]).await });
            return;
        }
        Plan::Post { text, secret } => (text, secret),
    };
    let role = role.to_string();
    tokio::spawn(async move {
        let url = std::env::var("CHORUS_PULSE_RECORD_URL")
            .unwrap_or_else(|_| "http://localhost:3475/api/record".to_string());
        let body = serde_json::json!({ "kind": "jeff", "to": role, "content": text });
        let r = role.clone();
        let sent = tokio::task::spawn_blocking(move || {
            ureq::post(&url)
                .timeout(std::time::Duration::from_secs(1))
                .set("X-Chorus-Pulse-Secret", &secret)
                .send_json(body)
                .map(|_| ())
                .map_err(|e| e.to_string())
        })
        .await;
        let why = match sent {
            Ok(Ok(())) => return,
            Ok(Err(e)) => e,
            Err(e) => e.to_string(),
        };
        chorus_log("terminal.input.unrecorded", &r, &[("error", why.as_str())]).await;
    });
}

#[cfg(test)]
mod tests {
    use super::{plan, typed_text, Plan};

    #[test]
    fn a_missing_secret_is_a_logged_miss_not_a_silent_failed_post() {
        assert_eq!(plan("go", None), Plan::Miss("no pulse secret"));
        assert_eq!(plan("go", Some("s".into())), Plan::Post { text: "go".into(), secret: "s".into() });
        // an injected prompt is skipped before the secret matters
        assert_eq!(plan("[nudge from kade | x] hi", None), Plan::Skip);
    }

    #[test]
    fn what_jeff_typed_or_pasted_is_recorded_as_typed() {
        assert_eq!(typed_text("ok router is in living room").as_deref(), Some("ok router is in living room"));
        // a message typed while the role was mid-turn arrives the same way
        assert_eq!(typed_text("its unplugged\n").as_deref(), Some("its unplugged"));
        // a paste is his too, line breaks and all
        let paste = "measured:\n  router 1 ms\n  .49 390 ms";
        assert_eq!(typed_text(paste).as_deref(), Some(paste));
    }

    #[test]
    fn a_slash_command_is_recorded_as_the_line_jeff_typed() {
        let p = "<command-message>pair</command-message>\n<command-name>/pair</command-name>\n<command-args>wren 4628</command-args>\nBase directory for this skill: ...";
        assert_eq!(typed_text(p).as_deref(), Some("/pair wren 4628"));
        assert_eq!(typed_text("<command-name>cws</command-name>").as_deref(), Some("/cws"));
    }

    // NEGATIVE PROOF: everything the harness or a peer put in the prompt is
    // skipped; recording any of these would write a second copy or a fake Jeff line.
    #[test]
    fn negative_proof_injected_prompts_are_never_recorded() {
        for p in [
            "[nudge from wren | 2026-10-19 16:53 Boston] Agree on the order",
            "<task-notification>\n<task-id>b1</task-id>\n</task-notification>",
            "Stop hook feedback:\n[chorus-hook-shim stop]: word-cap: 130 words",
            "[SYSTEM NOTIFICATION - NOT USER INPUT] background task done",
            "<system-reminder>reminder</system-reminder>",
            "   ",
        ] {
            assert_eq!(typed_text(p), None, "recorded an injected prompt: {p}");
        }
        // and the rule is a prefix rule: Jeff quoting a nudge mid-sentence is still his
        assert!(typed_text("why did [nudge from wren] arrive twice?").is_some());
    }
}
