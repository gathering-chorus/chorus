/// The crate's own version. Step 1 starts every product at 1.0.0; the bump rule
/// (#4478 Versions: removed field = major, added = minor) arrives with the diff check.
pub const CRATE_VERSION: &str = "1.0.0";

/// The shared token verifier, by path from `<step>/products/<product>/api/` (the
/// ADR-041 place for a product crate). A crate shipped away from this repo vendors it
/// (the export step, a later card).
pub const OIDC_PATH: &str = "../../../../platform/services/chorus-oidc";

/// The verifier's path from wherever the crate is written, so a crate placed at any
/// depth in the repo still finds it (Kade's review, #4490 run 1). The out folder must
/// sit inside the repo.
pub fn oidc_path(root: &std::path::Path, out: &std::path::Path) -> Result<String, String> {
    let root = std::fs::canonicalize(root).map_err(|e| format!("root: {e}"))?;
    std::fs::create_dir_all(out).map_err(|e| format!("out: {e}"))?;
    let out = std::fs::canonicalize(out).map_err(|e| format!("out: {e}"))?;
    let rel = out.strip_prefix(&root).map_err(|_| format!("{} is not inside {}", out.display(), root.display()))?;
    Ok(format!("{}platform/services/chorus-oidc", "../".repeat(rel.components().count())))
}

/// #4519 — the verifier's path from a crate written outside the Chorus repo (a product
/// repo like the wine diary): `--verifier <dir>` names the checkout of the shared
/// verifier. Build time only; the running API reaches no Chorus service.
pub fn verifier_path(verifier: &std::path::Path, out: &std::path::Path) -> Result<String, String> {
    let verifier = std::fs::canonicalize(verifier).map_err(|e| format!("verifier {}: {e}", verifier.display()))?;
    if !verifier.join("Cargo.toml").is_file() {
        return Err(format!("{} holds no Cargo.toml: not a verifier crate", verifier.display()));
    }
    std::fs::create_dir_all(out).map_err(|e| format!("out: {e}"))?;
    let out = std::fs::canonicalize(out).map_err(|e| format!("out: {e}"))?;
    let (a, b): (Vec<_>, Vec<_>) = (out.components().collect(), verifier.components().collect());
    let common = a.iter().zip(&b).take_while(|(x, y)| x == y).count();
    let up = "../".repeat(a.len() - common);
    let down: Vec<String> = b[common..].iter().map(|c| c.as_os_str().to_string_lossy().into_owned()).collect();
    Ok(format!("{up}{}", down.join("/")))
}

/// StreamEvent → stream-event: the kind that prefixes a row's IRI (v1's mint rule).
pub fn kebab(class: &str) -> String {
    let mut out = String::new();
    for (i, ch) in class.chars().enumerate() {
        if ch.is_ascii_uppercase() {
            if i > 0 {
                out.push('-');
            }
            out.push(ch.to_ascii_lowercase());
        } else {
            out.push(ch);
        }
    }
    out
}

fn setting<'a>(settings: &'a [(String, String)], key: &str) -> &'a str {
    settings.iter().find(|(k, _)| k == key).map_or("", |(_, v)| v.as_str())
}

fn lit(s: &str) -> String {
    format!("{s:?}")
}

pub fn model_rs(p: &Product, model_version: &str, settings: &[(String, String)]) -> String {
    let mut s = String::new();
    s.push_str(&format!(
        "//! {name}'s slice of the model. Generated by athena-gen — DO NOT EDIT; change the model.\n\n\
         pub const PRODUCT: &str = {pn};\npub const CRATE_VERSION: &str = env!(\"CARGO_PKG_VERSION\");\n\
         pub const API_VERSION: &str = \"v1\";\npub const MODEL_VERSION: &str = {mv};\npub const NS: &str = {ns};\n\
         pub const PREFIX: &str = {px};\npub const GRAPH_PREFIX: &str = {gp};\n\n",
        name = p.name, pn = lit(&p.name), mv = lit(model_version),
        // #4519 — the product's own namespace, prefix and graphs (generate refuses a
        // product that declares none, so these are never a Chorus default)
        ns = lit(setting(settings, "model.namespace")), px = lit(setting(settings, "model.prefix")),
        gp = lit(setting(settings, "store.graph_prefix"))
    ));
    s.push_str("/// Declared settings and their defaults, from the product's Property rows (see settings.rs for the lookup order).\npub const SETTINGS: &[(&str, &str)] = &[\n");
    for (k, v) in settings {
        s.push_str(&format!("    ({}, {}),\n", lit(&k), lit(&v)));
    }
    s.push_str("];\n\n");
    s.push_str(
        "pub struct FieldDef {\n    pub name: &'static str,\n    pub link: bool,\n    pub datatype: &'static str,\n    pub required: bool,\n    pub many: bool,\n    pub allowed: &'static [&'static str],\n    /// #4744 — on the product header (c:inHeader)\n    pub header: bool,\n    /// #4744 — the header shows rows newest first by this field (c:headerNewest)\n    pub newest: bool,\n    /// #4744 — the header shows only rows whose field holds this value (c:headerOnly)\n    pub header_only: Option<&'static str>,\n}\n\n\
         pub struct ClassDef {\n    pub domain: &'static str,\n    pub name: &'static str,\n    pub kind: &'static str,\n    pub plural: &'static str,\n    pub segment: &'static str,\n    pub graph: &'static str,\n    /// #4742 — homed in another product and composed here: read-only\n    pub composed: bool,\n    pub fields: &'static [FieldDef],\n}\n\n\
         pub const CLASSES: &[ClassDef] = &[\n",
    );
    for d in &p.domains {
        for c in &d.classes {
            s.push_str(&format!(
                "    ClassDef {{\n        domain: {}, name: {}, kind: {}, plural: {}, segment: {}, graph: {}, composed: {},\n        fields: &[\n",
                lit(&d.name), lit(&c.name), lit(&kebab(&c.name)), lit(&crate::model::pluralize(&c.name)), lit(&c.segment), lit(&c.graph), d.composed
            ));
            for f in &c.fields {
                let allowed: Vec<String> = f.allowed.iter().map(|a| lit(a)).collect();
                s.push_str(&format!(
                    "            FieldDef {{ name: {}, link: {}, datatype: {}, required: {}, many: {}, allowed: &[{}], header: {}, newest: {}, header_only: {} }},\n",
                    lit(&f.name),
                    matches!(f.kind, Kind::Link { .. }),
                    lit(match &f.kind { Kind::Literal { datatype } => datatype.as_str(), Kind::Link { .. } => "" }),
                    f.required,
                    f.many,
                    allowed.join(", "),
                    f.header,
                    f.newest,
                    f.header_only.as_ref().map_or_else(|| "None".to_string(), |v| format!("Some({})", lit(v)))
                ));
            }
            s.push_str("        ],\n    },\n");
        }
    }
    s.push_str("];\n");
    s
}

fn cargo_toml(p: &Product, oidc: &str) -> String {
    format!(
        "# Generated by athena-gen (#4490) — DO NOT EDIT; change the model or the generator.\n\
         [package]\nname = \"{n}-api\"\nversion = \"{CRATE_VERSION}\"\nedition = \"2021\"\n\
         description = \"The {n} product's API, generated from the Chorus model.\"\n\n\
         [dependencies]\nchorus-oidc = {{ path = \"{oidc}\" }}\nserde_json = \"1\"\ntiny_http = \"0.12\"\noxigraph = \"=0.5.11\"\nureq = {{ version = \"2\", features = [\"json\"] }}\n\n\
         [[bin]]\nname = \"{n}-api\"\npath = \"src/main.rs\"\n",
        n = p.name
    )
}

/// A template is tagged with the generator's own domain; the copy in a product's crate
/// carries the product's first domain instead, so the crawler places it (#4419).
fn retag(template: &str, domain: &str) -> String {
    let body = template.strip_prefix("// @domain: domains\n").unwrap_or(template);
    format!("// @domain: {domain}\n{body}")
}

/// Every file of the product's crate, keyed by path inside the crate, for a crate at
/// the ADR-041 product depth.
pub fn crate_files(p: &Product, model_version: &str, settings: &[(String, String)]) -> BTreeMap<String, String> {
    crate_files_with(p, model_version, settings, OIDC_PATH)
}

/// The same, with the verifier's path worked out from where the crate is written.
pub fn crate_files_with(p: &Product, model_version: &str, settings: &[(String, String)], oidc: &str) -> BTreeMap<String, String> {
    crate_files_ops(p, model_version, settings, oidc, &[])
}

/// The same, with each operation's handler path (from `handler_path`).
pub fn crate_files_ops(p: &Product, model_version: &str, settings: &[(String, String)], oidc: &str, handlers: &[(String, String)]) -> BTreeMap<String, String> {
    let domain = p.domains.first().map(|d| d.name.as_str()).unwrap_or("domains");
    let mut out = BTreeMap::new();
    out.insert("Cargo.toml".into(), cargo_toml(p, oidc));
    out.insert("src/auth.rs".into(), retag(AUTH, domain));
    out.insert("src/main.rs".into(), retag(MAIN, domain));
    out.insert("src/rules.rs".into(), retag(RULES, domain));
    out.insert("src/requirements_tests.rs".into(), retag(REQUIREMENTS, domain));
    out.insert("src/embedded_tests.rs".into(), retag(EMBEDDED_TESTS, domain));
    out.insert("src/door_tests.rs".into(), retag(DOOR_TESTS, domain));
    out.insert("tests/model.rs".into(), retag(MODEL_TEST, domain));
    out.insert("src/store.rs".into(), retag(STORE, domain));
    out.insert("src/settings.rs".into(), retag(SETTINGS, domain));
    out.insert("src/model.rs".into(), format!("// @domain: {domain}\n{}", model_rs(p, model_version, settings)));
    out.insert("src/ops.rs".into(), format!("// @domain: {domain}\n{}", ops_rs(p, handlers)));
    out
}

/// #4513 — the tool runner's input table: one JSON Schema per ToolInput shape,
/// keyed by the shape's name. The runner reads this file; nothing in it is
/// hand-written.
pub fn tool_inputs_json(inputs: &[(String, Vec<crate::model::ToolArg>)]) -> String {
    use serde_json::{json, Map, Value};
    let mut table = Map::new();
    for (shape, args) in inputs {
        let mut props = Map::new();
        let mut required = Vec::new();
        for a in args {
            let ty = match a.datatype.as_str() {
                "boolean" => "boolean",
                "integer" | "int" | "long" | "nonNegativeInteger" | "positiveInteger" => "integer",
                "decimal" | "double" | "float" => "number",
                _ => "string",
            };
            let mut item = Map::new();
            item.insert("type".into(), json!(ty));
            if !a.allowed.is_empty() {
                item.insert("enum".into(), json!(a.allowed));
            }
            if let Some(re) = &a.pattern {
                item.insert("pattern".into(), json!(re));
            }
            // #4514 — no sh:maxCount: an ordered list of that type
            let mut p = if a.many { let mut m = Map::new(); m.insert("type".into(), json!("array")); m.insert("items".into(), Value::Object(item)); m } else { item };
            if !a.description.is_empty() {
                p.insert("description".into(), json!(a.description));
            }
            if let Some(r) = &a.names_role {
                p.insert("namesRole".into(), json!(r));
            }
            props.insert(a.name.clone(), Value::Object(p));
            if a.required {
                required.push(json!(a.name));
            }
        }
        table.insert(shape.clone(), json!({ "type": "object", "properties": props, "required": required, "additionalProperties": false }));
    }
    let mut s = serde_json::to_string_pretty(&Value::Object(table)).unwrap_or_default();
    s.push('\n');
    s
}

/// #4444 reopen 2 — the runtime table chorus-principal and chorus-hook-shim
/// read (platform/services/shared/agent_runtimes.json). Generated from the
/// AgentRuntime rows; nothing in it is hand-written.
pub fn agent_runtimes_json(t: &crate::model::RuntimeTable) -> String {
    use serde_json::{json, Map, Value};
    let mut runtimes = Map::new();
    for (name, row) in &t.runtimes {
        let mut m = Map::new();
        for (k, v) in row {
            let one = k == "label" || t.single.iter().any(|s| s == k);
            m.insert(k.clone(), if one && v.len() == 1 { json!(v[0]) } else { json!(v) });
        }
        runtimes.insert(name.clone(), Value::Object(m));
    }
    let mut s = serde_json::to_string_pretty(&json!({ "runtimes": runtimes, "runsOn": t.runs_on })).unwrap_or_default();
    s.push('\n');
    s
}

/// #4742 — every route the product serves: `/<product>/<domain>/<collection>`.
pub fn routes(p: &Product) -> Vec<String> {
    // #4744 — the product root is its header, served only when some domain puts a field on it
    let root = (!header(p).is_empty()).then(|| format!("/{}", p.name));
    root.into_iter()
        .chain(p.domains.iter().flat_map(|d| d.classes.iter().map(move |c| format!("/{}/{}/{}", p.name, d.name, c.segment))))
        .chain(p.operations.iter().map(|o| format!("/{}/{}/{}", p.name, o.domain, o.segment)))
        .collect()
}

/// #4744 — an operation's handler, as a path from the crate's `src/` (where `ops.rs` names
/// it). A handler that is not in the repo is refused by name: nothing is generated around it.
pub fn handler_path(root: &std::path::Path, out: &std::path::Path, op: &crate::model::Operation) -> Result<String, String> {
    let h = root.join(&op.handler);
    if !h.is_file() {
        return Err(format!("operation {} names handler {}, which does not exist", op.name, op.handler));
    }
    let h = std::fs::canonicalize(&h).map_err(|e| format!("handler: {e}"))?;
    std::fs::create_dir_all(out.join("src")).map_err(|e| format!("out: {e}"))?;
    let src = std::fs::canonicalize(out.join("src")).map_err(|e| format!("out: {e}"))?;
    let (a, b): (Vec<_>, Vec<_>) = (src.components().collect(), h.components().collect());
    let common = a.iter().zip(&b).take_while(|(x, y)| x == y).count();
    let down: Vec<String> = b[common..].iter().map(|c| c.as_os_str().to_string_lossy().into_owned()).collect();
    Ok(format!("{}{}", "../".repeat(a.len() - common), down.join("/")))
}

/// #4744 — `src/ops.rs`: one module per operation, from its handler's path, and the
/// dispatch the product's routes call. Each handler is `pub fn run(ctx, rest, query)`.
pub fn ops_rs(p: &Product, handler_paths: &[(String, String)]) -> String {
    let mut s = String::from("//! The product's operations. Generated by athena-gen — DO NOT EDIT; change the model.\n\nuse serde_json::Value;\n\n");
    for (name, path) in handler_paths {
        s.push_str(&format!("#[path = {}]\npub mod {};\n", lit(path), name.replace('-', "_")));
    }
    // an operation generated with no handler path fails the crate's build by name, never routes to nothing
    for o in p.operations.iter().filter(|o| !handler_paths.iter().any(|(n, _)| *n == o.name.replace('-', "_"))) {
        s.push_str(&format!("compile_error!({});\n", lit(&format!("operation {} has no handler: generate with its handlerPath", o.name))));
    }
    let pairs: Vec<String> = p.operations.iter().map(|o| format!("({}, {})", lit(&o.domain), lit(&o.segment))).collect();
    s.push_str(&format!("\n/// Is `/<product>/<domain>/<segment>` an operation?\npub fn has(domain: &str, segment: &str) -> bool {{\n    let ops: &[(&str, &str)] = &[{}];\n    ops.contains(&(domain, segment))\n}}\n", pairs.join(", ")));
    s.push_str("\n/// The operation served at `/<product>/<domain>/<segment>[/<rest>…]`, if any.\npub fn route(ctx: &crate::Ctx, domain: &str, segment: &str, rest: &[&str], query: &str) -> Option<(u16, Value)> {\n    match (domain, segment) {\n");
    for o in &p.operations {
        s.push_str(&format!("        ({}, {}) => Some({}::run(ctx, rest, query)),\n", lit(&o.domain), lit(&o.segment), o.name.replace('-', "_")));
    }
    s.push_str("        _ => { let _ = (ctx, rest, query); None }\n    }\n}\n");
    s
}

/// #4744 — the product's header: `<domain>.<segment>.<field>` for every field marked
/// `c:inHeader` in a domain the product owns or composes, in domain order.
pub fn header(p: &Product) -> Vec<String> {
    p.domains.iter()
        .flat_map(|d| d.classes.iter().flat_map(move |c| c.fields.iter().filter(|f| f.header)
            .map(move |f| format!("{}.{}.{}", d.name, c.segment, f.name))))
        .collect()
}

/// #4742 gap 8 (#4708) — the routes an already generated crate serves (read from its
/// model.rs) that `p` would no longer serve. A class that falls out of the model is named,
/// never dropped silently.
pub fn dropped_routes(old_model_rs: &str, p: &Product) -> Vec<String> {
    let now = routes(p);
    old_routes(old_model_rs, &p.name).into_iter().filter(|r| !now.contains(r)).collect()
}

/// The routes a generated model.rs serves, read from its ClassDef lines. Empty when the text
/// holds none it can read; generate treats that as a refusal, never as "nothing dropped".
pub fn old_routes(model_rs: &str, product: &str) -> Vec<String> {
    let quoted = |line: &str, key: &str| {
        let rest = &line[line.find(&format!("{key}: \""))? + key.len() + 3..];
        Some(rest[..rest.find('"')?].to_string())
    };
    model_rs
        .lines()
        .filter_map(|l| Some(format!("/{product}/{}/{}", quoted(l, "domain")?, quoted(l, "segment")?)))
        .collect()
}
