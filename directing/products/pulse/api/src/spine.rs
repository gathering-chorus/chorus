// @domain: awareness
//! #4766 — a class whose shape says `chorus:instancesStore "spine"` is read from the spine
//! log, where its rows already live (Jeff 2026-11-16: "loki is not system of record"; the
//! spine is). Nothing is copied: each read takes the log's last bytes and turns them into
//! rows. Never the whole file — the spine is ~700 MB and a whole-file read froze the API
//! once already.
//! One row is one tool call. The hooks write `agent.action` phase=started when a call
//! begins and phase=ended when it ends, both carrying `call_id`; the row joins them on that
//! id. A call with no end is running, unless its session's turn ended since: then it
//! stopped. Replies, nudges and turn lines are never rows, so a reply-only turn is not work.
//! Generated by athena-gen from its template — DO NOT EDIT; change the generator.

use crate::model::ClassDef;
use crate::store::{Row, RowStore, Where};
use crate::spine_log::{calls, tail, Call};
use serde_json::json;
pub use crate::spine_log::TAIL_BYTES;

/// A call as the class's row: name = call id, label = what it did, and each shape field
/// filled by what its name ends with (…Role, …Tool, …Phase, …Ts, …Session, …Card).
pub fn row(class: &ClassDef, c: &Call) -> Row {
    let mut r = Row::new();
    r.insert("name".into(), json!(c.id));
    r.insert("label".into(), json!(c.what));
    r.insert("status".into(), json!(c.phase));
    for f in class.fields {
        let n = f.name.to_ascii_lowercase();
        let v = [("role", &c.role), ("tool", &c.tool), ("phase", &c.phase), ("ts", &c.ts), ("session", &c.session), ("card", &c.card)]
            .iter().find(|(k, _)| n.ends_with(k)).map(|(_, v)| (*v).clone()).unwrap_or_default();
        r.insert(f.name.into(), json!(v));
    }
    r
}

fn matches(r: &Row, w: &Where) -> bool {
    let get = |k: &str| r.get(k).and_then(|v| v.as_str()).unwrap_or("").to_string();
    w.eq.iter().all(|(k, v)| get(k) == *v)
        && w.q.as_ref().map_or(true, |q| get("label").to_lowercase().contains(&q.to_lowercase()))
        && w.bounds.iter().all(|(k, op, v)| if *op == "<" { get(k) < *v } else { get(k) > *v })
}

/// The rows of every spine class: read-only, from the log's end.
pub struct SpineRows {
    pub path: String,
    pub max: u64,
}

impl SpineRows {
    fn all(&self, class: &ClassDef) -> Result<Vec<Row>, String> {
        Ok(calls(&tail(&self.path, self.max)?).iter().map(|c| row(class, c)).collect())
    }
    fn page(rows: Vec<Row>, limit: usize, offset: usize) -> (Vec<Row>, usize) {
        let total = rows.len();
        (rows.into_iter().skip(offset).take(limit).collect(), total)
    }
}

const READ_ONLY: &str = "spine rows are written by the hooks, never through the API";

impl RowStore for SpineRows {
    fn list(&self, class: &ClassDef, limit: usize, offset: usize) -> Result<(Vec<Row>, usize), String> {
        Ok(Self::page(self.all(class)?, limit, offset))
    }
    fn get(&self, class: &ClassDef, name: &str) -> Result<Option<Row>, String> {
        Ok(self.all(class)?.into_iter().find(|r| r["name"] == json!(name)))
    }
    fn exists(&self, _iri: &str) -> Result<bool, String> { Ok(false) }
    fn version_count(&self, _of_row: &str) -> Result<usize, String> { Ok(0) }
    fn write(&self, _g: &str, _s: &str, _t: Option<&str>, _f: &[(String, Vec<crate::rules::Cell>)], _w: bool) -> Result<(), String> {
        Err(READ_ONLY.into())
    }
    fn delete(&self, _g: &str, _s: &str) -> Result<(), String> { Err(READ_ONLY.into()) }
    fn list_seen_by(&self, class: &ClassDef, limit: usize, offset: usize, _viewer: &str) -> Result<(Vec<Row>, usize), String> {
        self.list(class, limit, offset)
    }
    fn get_seen_by(&self, class: &ClassDef, name: &str, _viewer: &str) -> Result<Option<Row>, String> {
        self.get(class, name)
    }
    fn list_where(&self, class: &ClassDef, limit: usize, offset: usize, _viewer: Option<&str>, w: &Where) -> Result<(Vec<Row>, usize), String> {
        let mut rows: Vec<Row> = self.all(class)?.into_iter().filter(|r| matches(r, w)).collect();
        if let Some((k, desc)) = &w.sort {
            rows.sort_by(|a, b| {
                let (x, y) = (a.get(k).and_then(|v| v.as_str()).unwrap_or(""), b.get(k).and_then(|v| v.as_str()).unwrap_or(""));
                if *desc { y.cmp(x) } else { x.cmp(y) }
            });
        }
        Ok(Self::page(rows, limit, offset))
    }
}

/// Each class read from where its shape says its rows live.
pub struct Routed {
    pub graph: Box<dyn RowStore>,
    pub spine: SpineRows,
}

impl Routed {
    fn of(&self, class: &ClassDef) -> &dyn RowStore {
        if class.store == "spine" { &self.spine } else { self.graph.as_ref() }
    }
}

impl RowStore for Routed {
    fn list(&self, c: &ClassDef, l: usize, o: usize) -> Result<(Vec<Row>, usize), String> { self.of(c).list(c, l, o) }
    fn get(&self, c: &ClassDef, n: &str) -> Result<Option<Row>, String> { self.of(c).get(c, n) }
    fn exists(&self, iri: &str) -> Result<bool, String> { self.graph.exists(iri) }
    fn version_count(&self, of_row: &str) -> Result<usize, String> { self.graph.version_count(of_row) }
    fn write(&self, g: &str, s: &str, t: Option<&str>, f: &[(String, Vec<crate::rules::Cell>)], w: bool) -> Result<(), String> {
        self.graph.write(g, s, t, f, w)
    }
    fn delete(&self, g: &str, s: &str) -> Result<(), String> { self.graph.delete(g, s) }
    fn list_seen_by(&self, c: &ClassDef, l: usize, o: usize, v: &str) -> Result<(Vec<Row>, usize), String> { self.of(c).list_seen_by(c, l, o, v) }
    fn get_seen_by(&self, c: &ClassDef, n: &str, v: &str) -> Result<Option<Row>, String> { self.of(c).get_seen_by(c, n, v) }
    fn list_where(&self, c: &ClassDef, l: usize, o: usize, v: Option<&str>, w: &Where) -> Result<(Vec<Row>, usize), String> {
        self.of(c).list_where(c, l, o, v, w)
    }
}
